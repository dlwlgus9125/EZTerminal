export function attachAIProfiles(journeys){
 for(const j of journeys){
  if(visitProfiles[j.id].length!==j.scenes.length)throw new Error(j.id+': AI visit mapping mismatch');
  j.scenes.forEach((scene,i)=>{
   const profileId=visitProfiles[j.id][i];
   scene.ai={profileId,mode:profileId?(observedVisits.has(scene.key)?'observe':'request'):'manual'};
  });
  j.recovery.ai={profileId:j.id==='U02'?'builder':null,mode:j.id==='U02'?'request':'manual'};
 }
}

