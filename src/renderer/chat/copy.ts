function ordinal(position: number): string {
  const tens = position % 100;
  const suffix = tens >= 11 && tens <= 13 ? 'th' : position % 10 === 1 ? 'st' : position % 10 === 2 ? 'nd' : position % 10 === 3 ? 'rd' : 'th';
  return `${position}${suffix}`;
}

